#!/usr/bin/env python3
"""Compile only call-free basic blocks of the original sprite setup method.
Calls, returns, fibers and class initialization remain in OEVM. Live stack,
locals, last-PC and exception boundaries remain the original JVM frame.
"""
import hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'game/data/classes.json';classes=json.loads(source.read_text())
m=classes['k']['methods']['g(I)V'];code=m['code']
assert not m['exceptions'] and m['flags']&8 and not m['flags']&32
starts={0}
for pc,ins in enumerate(code):
 op=ins[0]
 if 153<=op<=167 or op in [198,199]: starts|={pc+1,ins[1]}
 if op in [177,182,184]: starts|={pc,pc+1}
starts=sorted(p for p in starts if p<len(code))
blocks=[(s,starts[n+1] if n+1<len(starts) else len(code)) for n,s in enumerate(starts)]
blocks=[(s,e) for s,e in blocks if e-s>=2 and code[s][0] not in [177,182,184]]
q=lambda v:json.dumps(v,ensure_ascii=False)
def field_owner(ref):
 owner=ref['owner']
 while owner in classes:
  if any(f['name']==ref['name'] and f['desc']==ref['desc'] for f in classes[owner]['fields']):return owner
  owner=classes[owner]['parent']
 raise ValueError(ref)
owners=sorted({field_owner(i[1]) for i in code if i[0] in [178,179]})
lines=['# Generated by tools/compile_sprite_blocks.py; original bytecode is the source.',f'# classes.json SHA256 {hashlib.sha256(source.read_bytes()).hexdigest()}',
'class_name OESpriteBlocks','extends RefCounted','var vm: OEVM','',
'func _init(machine: OEVM) -> void:','\tvm=machine',f'\tassert(vm.classes.k.methods["g(I)V"].code.size()=={len(code)})',
'\tvm.classes.k.methods["g(I)V"].sprite_blocks='+str({s:e for s,e in blocks}),'',
'func ready() -> bool:', '\treturn '+' and '.join(f'vm.initialized.has({q(o)})' for o in owners),'',
'func invoke(frame: Dictionary) -> void:','\tvar stack: Array=frame.stack','\tvar local: Array=frame.locals','\tmatch int(frame.pc):']
for start,end in blocks:
 lines.append(f'\t\t{start}:')
 def emit(s):lines.append('\t\t\t'+s)
 serial=0
 def temp(expr):
  global serial
  name=f't{start}_{serial}';serial+=1;emit(f'var {name}: Variant={expr}');return name
 def pop():return temp('stack.pop_back()')
 def push(expr):emit(f'stack.append({expr})')
 def location(pc):emit(f'frame.pc={pc+1};frame.last={pc}')
 def check():emit('if vm.exception!=null: return')
 terminal=False
 for pc,ins in enumerate(code[start:end],start):
  op=ins[0]
  if op==1:push('null')
  elif 2<=op<=8:push(str(op-3))
  elif op in [16,17,19,20]:
   v=ins[1];push(f'JLong.new({v["v"]})' if isinstance(v,dict) else str(v))
  elif op in [21,25]:push(f'local[{ins[1]}]')
  elif 26<=op<=29:push(f'local[{op-26}]')
  elif op in [54,58]:emit(f'local[{ins[1]}]=stack.pop_back()')
  elif 59<=op<=62:emit(f'local[{op-59}]=stack.pop_back()')
  elif op in [46,50,53]:
   location(pc);index=pop();array=pop()
   value=temp(f'vm.geometry.aload({array},int({index}))');check();push(value)
  elif op==79:
   location(pc);value=pop();index=pop();array=pop()
   emit(f'vm.geometry.astore({array},int({index}),{value},{op})');check()
  elif op==87:emit('stack.pop_back()')
  elif op==89:push('stack.back()')
  elif op in [96,100,104,105,120,122,123,126,128,130]:
   right=pop();left=pop();a=f'OEVM.number({left})' if op in [105,123] else f'int({left})';b=f'OEVM.number({right})' if op in [105,123] else f'int({right})'
   sign={96:'+',100:'-',104:'*',105:'*',120:'<<',122:'>>',123:'>>',126:'&',128:'|',130:'^'}[op]
   if op in [120,122,123]:b=f'({b}&{63 if op==123 else 31})'
   push(f'{"JLong.new" if op in [105,123] else "OEVM.i32"}({a}{sign}{b})')
  elif op==132:emit(f'local[{ins[1]}]=OEVM.i32(int(local[{ins[1]}])+({ins[2]}))')
  elif op==133:push(f'JLong.new(int({pop()}))')
  elif op==136:push(f'OEVM.i32(OEVM.number({pop()}))')
  elif op==147:push(f'OEVM.signed(int({pop()}),16)')
  elif op==178:
   r=ins[1];push(f'vm.statics[{q(field_owner(r))}][{q(r["name"]+":"+r["desc"])}]')
  elif op in [180,181]:
   location(pc);r=ins[1];value=pop() if op==181 else '';obj=pop()
   emit(f'if {obj}==null: vm.throw_exception("java/lang/NullPointerException");return')
   if op==180:push(f'vm.get_field({obj},{q(r["owner"])},{q(r["name"])},{q(r["desc"])})')
   else:emit(f'vm.set_field({obj},{q(r["owner"])},{q(r["name"])},{q(r["desc"])},{value})')
  elif 153<=op<=164 or op in [198,199]:
   if op in [198,199]:a=pop();cond=f'{a}{"==" if op==198 else "!="}null'
   elif op<=158:a=pop();cond=f'int({a})'+{153:'==',154:'!=',155:'<',156:'>=',157:'>',158:'<='}[op]+'0'
   else:b=pop();a=pop();cond=f'{a}'+{159:'==',160:'!=',161:'<',162:'>=',163:'>',164:'<='}[op]+b
   emit(f'frame.pc={ins[1]} if {cond} else {pc+1};frame.last={pc}');terminal=True
  elif op==167:emit(f'frame.pc={ins[1]};frame.last={pc}');terminal=True
  else:raise ValueError((pc,ins))
 if not terminal:emit(f'frame.pc={end};frame.last={end-1}')
(ROOT/'game/core/sprite_blocks.gd').write_text('\n'.join(lines)+'\n')
print('Generated',len(blocks),'blocks;',sum(e-s for s,e in blocks),'instructions;',len(lines),'lines')
